    /** Finds a stream at the given height, preferring MP4 container. */
    private static VideoStream findByHeight(List<VideoStream> list, int h) {
        VideoStream fallback = null;
        for (VideoStream v : list) {
            if (parseHeight(v.getResolution()) != h) continue;
            if (v.getFormat() == MediaFormat.MPEG_4) return v;
            if (fallback == null) fallback = v;
        }
        return fallback;
    }

    private static boolean isOpus(AudioStream a) {
        MediaFormat f = a.getFormat();
        return f == MediaFormat.OPUS || f == MediaFormat.WEBMA_OPUS
                || f == MediaFormat.WEBMA;
    }

    /** Best audio stream; restrict to AAC (m4a) or Opus-family when asked. */
    private static AudioStream bestAudio(List<AudioStream> list,
                                         boolean m4aOnly, boolean opusOnly) {
        AudioStream best = null;
        for (AudioStream a : list) {
            if (m4aOnly && a.getFormat() != MediaFormat.M4A) continue;
            if (opusOnly && !isOpus(a)) continue;
            if (a.getAverageBitrate() <= 0) continue;
            if (best == null || a.getAverageBitrate() > best.getAverageBitrate()) {
                best = a;
            }
        }
        return best;
    }

    /** Worst audio stream; restrict to AAC (m4a) when asked. */
    private static AudioStream worstAudio(List<AudioStream> list, boolean m4aOnly) {
        AudioStream worst = null;
        for (AudioStream a : list) {
            if (m4aOnly && a.getFormat() != MediaFormat.M4A) continue;
            if (a.getAverageBitrate() <= 0) continue;
            if (worst == null || a.getAverageBitrate() < worst.getAverageBitrate()) {
                worst = a;
            }
        }
        return worst;
    }

    // ---------- mux stream collection & 403 recovery ----------

    /** Collects DASH video-only streams, classified by muxable container.
     *  DASH streams live in getVideoOnlyStreams() (getVideoStreams() is
     *  progressive-only in this extractor version). AV1 itags 394-401 are
     *  excluded: Android's MediaMuxer cannot mux AV1. */
    static void collectVideoOnly(StreamExtractor ex,
                                List<VideoStream> voAvc, List<VideoStream> voVp9)
            throws Exception {
        for (VideoStream v : ex.getVideoStreams()) {
            if (v.isVideoOnly()) classifyVo(v, voAvc, voVp9);
        }
        for (VideoStream v : ex.getVideoOnlyStreams()) {
            classifyVo(v, voAvc, voVp9);
        }
    }

    private static void classifyVo(VideoStream v,
                                   List<VideoStream> voAvc, List<VideoStream> voVp9) {
        int itag = -1;
        try { itag = v.getItag(); } catch (Exception ignored) {}
        if (v.getFormat() == MediaFormat.MPEG_4) {
            if (itag >= 394 && itag <= 401) return; // AV1 in MP4 — not muxable
            voAvc.add(v);
        } else if (v.getFormat() == MediaFormat.WEBM) {
            voVp9.add(v);
        }
    }

    public static class MuxStreams {
        public final String videoUrl, audioUrl;
        MuxStreams(String v, String a) { videoUrl = v; audioUrl = a; }
    }

    /** Re-resolves mux stream URLs for a given ladder height/container.
     *  Used for HTTP 403 recovery: YouTube stream URLs are ephemeral
     *  (expire / IP-bound), so on 403 we fetch fresh ones and retry once. */
    public static MuxStreams resolveMuxStreams(String videoId, int height, boolean webm) {
        try {
            ensureInit();
            StreamingService service = ServiceList.YouTube;
            StreamExtractor ex = service.getStreamExtractor(
                    "https://www.youtube.com/watch?v=" + videoId);
            ex.fetchPage();
            List<VideoStream> voAvc = new ArrayList<>();
            List<VideoStream> voVp9 = new ArrayList<>();
            collectVideoOnly(ex, voAvc, voVp9);
            VideoStream v = findByHeight(webm ? voVp9 : voAvc, height);
            if (v == null) return null;
            AudioStream a = webm ? bestAudio(ex.getAudioStreams(), false, true)
                                 : bestAudio(ex.getAudioStreams(), true, false);
            if (a == null) a = bestAudio(ex.getAudioStreams(), false, false);
            if (a == null) return null;
            return new MuxStreams(v.getContent(), a.getContent());
        } catch (Exception e) {
            return null;
        }
    }

