    public static String extractVideoId(String url) {
        if (url == null) return null;
        Matcher m = Pattern.compile("[?&]v=([\\w-]{6,})").matcher(url);
        if (m.find()) return m.group(1);
        m = Pattern.compile("youtu\\.be/([\\w-]{6,})").matcher(url);
        if (m.find()) return m.group(1);
        m = Pattern.compile("/shorts/([\\w-]{6,})").matcher(url);
        if (m.find()) return m.group(1);
        return null;
    }

    public static String thumbUrl(String videoId) {
        return videoId == null ? null
                : "https://i.ytimg.com/vi/" + videoId + "/hqdefault.jpg";
    }

    public static String fmtDuration(long sec) {
        if (sec <= 0) return "";
        long h = sec / 3600, m = (sec % 3600) / 60, s = sec % 60;
        if (h > 0) return String.format("%d:%02d:%02d", h, m, s);
        return String.format("%02d:%02d", m, s);
    }

