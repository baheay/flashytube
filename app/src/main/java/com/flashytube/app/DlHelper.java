    public static void fetchVideoAndPick(final Activity act, final String url,
                                         final boolean finishAfter,
                                         final boolean wifiDefault) {
        final ProgressDialog pd = new ProgressDialog(act);
        pd.setMessage(act.getString(R.string.prog_fetch));
        // Cancelable: on slow networks the user must be able to bail out
        // instead of staring at a spinner (fetchPage + probes can take minutes).
        final AtomicBoolean cancelled = new AtomicBoolean(false);
        pd.setCancelable(true);
        pd.setOnCancelListener(d -> cancelled.set(true));
        pd.show();
        new Thread(() -> {
            try {
                StreamingService service = ServiceList.YouTube;
                StreamExtractor ex = service.getStreamExtractor(url);
                ex.fetchPage();
                if (cancelled.get()) return;
                final String title = clean(ex.getName());
                final String vid = extractVideoId(url);
                long dur = 0;
                try { dur = ex.getLength(); } catch (Exception ignored) {}
                final long durationSec = dur;
                // uploader + publish date for the dialog header
                String uploader = "";
                try { uploader = ex.getUploaderName(); } catch (Exception ignored) {}
                if (uploader == null) uploader = "";
                String uploadDate = "";
                try { uploadDate = fmtUploadDate(ex.getUploadDate()); }
                catch (Exception ignored) {}
                final String metaUploader = uploader;
                final String metaDate = uploadDate;
                final List<Item> items = new ArrayList<>();

                // 1) video ladder 144p -> 1080p (SnapTube style):
                //    progressive first, then avc1+AAC muxed to MP4,
                //    then vp9+Opus muxed to WebM (av01 skipped: MediaMuxer can't mux AV1)
                //    Candidates are picked first; sizes are probed in PARALLEL
                //    (4 threads) so slow networks don't stall on ~10 serial HEADs.
                final List<Item> videoItems = new ArrayList<>();
                final List<Item> audioItems = new ArrayList<>();
                {
                    List<VideoStream> prog = new ArrayList<>();
                    for (VideoStream v : ex.getVideoStreams()) {
                        if (!v.isVideoOnly()) prog.add(v);
                    }
                    List<VideoStream> voAvc = new ArrayList<>();
                    List<VideoStream> voVp9 = new ArrayList<>();
                    collectVideoOnly(ex, voAvc, voVp9);
                    AudioStream bestM4a = bestAudio(ex.getAudioStreams(), true, false);
                    AudioStream bestOpus = bestAudio(ex.getAudioStreams(), false, true);

                    class Cand { int h; VideoStream prog, avc, vp9; }
                    List<Cand> cands = new ArrayList<>();
                    int[] ladder = {144, 240, 360, 480, 720, 1080};
                    for (int h : ladder) {
                        if (cancelled.get()) return;
                        Cand c = new Cand();
                        c.h = h;
                        c.prog = findByHeight(prog, h);
                        if (c.prog == null) {
                            c.avc = findByHeight(voAvc, h);
                            if (c.avc != null && bestM4a == null) c.avc = null;
                            if (c.avc == null) {
                                c.vp9 = findByHeight(voVp9, h);
                                if (c.vp9 != null && bestOpus == null) c.vp9 = null;
                            }
                        }
                        if (c.prog != null || c.avc != null || c.vp9 != null) cands.add(c);
                    }

                    // 2) audio: exactly two deduped options — high and low
                    AudioStream high = bestAudio(ex.getAudioStreams(), true, false);
                    if (high == null) high = bestAudio(ex.getAudioStreams(), false, false);
                    AudioStream low = worstAudio(ex.getAudioStreams(), true);
                    if (low == null) low = worstAudio(ex.getAudioStreams(), false);
                    if (low == high) low = null;

                    Set<String> purls = new LinkedHashSet<>();
                    for (Cand c : cands) {
                        if (c.prog != null) purls.add(c.prog.getContent());
                        else if (c.avc != null) {
                            purls.add(c.avc.getContent());
                            purls.add(bestM4a.getContent());
                        } else if (c.vp9 != null) {
                            purls.add(c.vp9.getContent());
                            purls.add(bestOpus.getContent());
                        }
                    }
                    if (high != null) purls.add(high.getContent());
                    if (low != null) purls.add(low.getContent());
                    Map<String, Long> sizes = probeSizesParallel(purls, cancelled);
                    if (cancelled.get()) return;

                    for (Cand c : cands) {
                        if (c.prog != null) {
                            String res = c.prog.getResolution();
                            String size = fmtSize(sizeOf(sizes, c.prog.getContent()));
                            String label = size.isEmpty()
                                    ? act.getString(R.string.fmt_video_nosize, res)
                                    : act.getString(R.string.fmt_video, res, size);
                            videoItems.add(new Item(label,
                                    title + " " + res + "." + c.prog.getFormat().getSuffix(),
                                    c.prog.getContent(), null, "video"));
                        } else if (c.avc != null) {
                            String res = c.avc.getResolution();
                            long sz = sizeOf(sizes, c.avc.getContent())
                                    + sizeOf(sizes, bestM4a.getContent());
                            String size = fmtSize(sz);
                            String label = size.isEmpty()
                                    ? act.getString(R.string.fmt_video_nosize, res)
                                    : act.getString(R.string.fmt_video, res, size);
                            Item avcItem = new Item(label, title + " " + res + ".mp4",
                                    c.avc.getContent(), bestM4a.getContent(), "video");
                            avcItem.muxHeight = c.h;
                            videoItems.add(avcItem);
                        } else if (c.vp9 != null) {
                            String res = c.vp9.getResolution();
                            long sz = sizeOf(sizes, c.vp9.getContent())
                                    + sizeOf(sizes, bestOpus.getContent());
                            String size = fmtSize(sz);
                            String label = size.isEmpty()
                                    ? act.getString(R.string.fmt_video_nosize, res)
                                    : act.getString(R.string.fmt_video, res, size);
                            Item vp9Item = new Item(label, title + " " + res + ".webm",
                                    c.vp9.getContent(), bestOpus.getContent(), "video");
                            vp9Item.muxHeight = c.h;
                            vp9Item.muxWebm = true;
                            videoItems.add(vp9Item);
                        }
                    }

                    if (high != null) {
                        int br = high.getAverageBitrate();
                        String size = fmtSize(sizeOf(sizes, high.getContent()));
                        String label = size.isEmpty()
                                ? act.getString(R.string.fmt_audio_high_nosize, br)
                                : act.getString(R.string.fmt_audio_high, br, size);
                        audioItems.add(new Item(label,
                                title + " audio-high." + high.getFormat().getSuffix(),
                                high.getContent(), null, "audio"));
                    }
                    if (low != null) {
                        int br = low.getAverageBitrate();
                        String size = fmtSize(sizeOf(sizes, low.getContent()));
                        String label = size.isEmpty()
                                ? act.getString(R.string.fmt_audio_low_nosize, br)
                                : act.getString(R.string.fmt_audio_low, br, size);
                        audioItems.add(new Item(label,
                                title + " audio-low." + low.getFormat().getSuffix(),
                                low.getContent(), null, "audio"));
                    }
                }

                // 3) subtitles
                final List<Item> subItems = new ArrayList<>();
                List<SubtitlesStream> subs = ex.getSubtitles(MediaFormat.VTT);
                if (subs.isEmpty()) subs = ex.getSubtitles(MediaFormat.TTML);
                for (SubtitlesStream s : subs) {
                    String auto = s.isAutoGenerated()
                            ? act.getString(R.string.sub_auto) : "";
                    subItems.add(new Item(
                            act.getString(R.string.fmt_sub, s.getDisplayLanguageName(), auto),
                            title + "." + s.getLanguageTag() + "." + s.getExtension(),
                            s.getContent(), null, "sub"));
                }
                // AR/EN subtitles for the "also download" checkboxes.
                final List<SubtitlesStream> arEnSubs = pickArEnSubtitles(ex);

                act.runOnUiThread(() -> {
                    if (cancelled.get() || uiGone(act)) return;
                    pd.dismiss();
                    if (videoItems.isEmpty() && audioItems.isEmpty()
                            && subItems.isEmpty()) {
                        Toast.makeText(act, R.string.toast_no_qualities,
                                Toast.LENGTH_LONG).show();
                        if (finishAfter) act.finish();
                        return;
                    }
                    showQualityDialog(act, title, vid, durationSec, videoItems,
                            audioItems, subItems, arEnSubs, finishAfter,
                            metaUploader, metaDate, wifiDefault);
                });
            } catch (Exception e) {
                if (cancelled.get()) return;
                // Age-restricted + logged in: the extractor's mobile clients
                // don't honor the web session, so retry via the WEB player.
                if (e instanceof org.schabi.newpipe.extractor.exceptions
                        .AgeRestrictedContentException
                        && GoogleLogin.isLoggedIn(act)) {
                    final String webVid = extractVideoId(url);
                    WebPlayer.lastReason = "";
                    WebPlayer.Result wr = webVid != null
                            ? WebPlayer.fetch(webVid) : null;
                    // Last resort: hidden WebView runs YouTube's own JS
                    // (BotGuard/PO token) exactly like the working browser.
                    if ((wr == null || wr.formats.isEmpty())
                            && webVid != null) {
                        WebViewPlayer.Result wvr =
                                WebViewPlayer.fetch(act, webVid);
                        if (wvr != null && !wvr.formats.isEmpty()) {
                            wr = new WebPlayer.Result();
                            wr.title = wvr.title;
                            wr.formats.addAll(wvr.formats);
                        }
                    }
                    if (wr != null && !wr.formats.isEmpty()) {
                        final List<Item> webItems = new ArrayList<>();
                        final String wTitle = wr.title != null
                                && !wr.title.isEmpty()
                                ? clean(wr.title) : "video";
                        for (WebPlayer.Format f : wr.formats) {
                            String fn = wTitle + ".mp4";
                            String lbl = f.label
                                    + (f.hasAudio ? "" : " (بدون صوت)");
                            webItems.add(new Item(lbl, fn, f.url, null,
                                    "video"));
                        }
                        act.runOnUiThread(() -> {
                            if (cancelled.get() || uiGone(act)) return;
                            pd.dismiss();
                            showQualityDialog(act, wTitle, webVid, 0,
                                    webItems, new ArrayList<>(),
                                    new ArrayList<>(), new ArrayList<>(),
                                    finishAfter, "", "", wifiDefault);
                        });
                        return;
                    }
                }
                fail(act, pd, e, finishAfter);
            }
        }).start();
    }

