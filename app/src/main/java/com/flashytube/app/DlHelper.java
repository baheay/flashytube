    /** SnapTube-style sectioned quality dialog: video ladder, 2 audios, subtitles. */
    private static void showQualityDialog(final Activity act, final String title,
                                          final String vid, final long durationSec,
                                          final List<Item> videoItems,
                                          final List<Item> audioItems,
                                          final List<Item> subItems,
                                          final List<SubtitlesStream> arEnSubs,
                                          final boolean finishAfter,
                                          final String uploader,
                                          final String uploadDate,
                                          final boolean wifiDefault) {
        ScrollView sv = new ScrollView(act);
        LinearLayout root = new LinearLayout(act);
        root.setOrientation(LinearLayout.VERTICAL);
        float density = act.getResources().getDisplayMetrics().density;
        int pad = (int) (12 * density);
        root.setPadding(pad, pad / 2, pad, pad / 2);
        sv.addView(root);

        // channel name + publish date under the title
        StringBuilder meta = new StringBuilder();
        if (uploader != null && !uploader.isEmpty()) meta.append("📺 ").append(uploader);
        if (uploadDate != null && !uploadDate.isEmpty()) {
            if (meta.length() > 0) meta.append("  •  ");
            meta.append("📅 ").append(uploadDate);
        }
        if (meta.length() > 0) {
            TextView mt = new TextView(act);
            mt.setText(meta.toString());
            mt.setTextSize(13);
            mt.setPadding(pad / 2, 0, pad / 2, pad / 2);
            root.addView(mt);
        }

        final AlertDialog[] dlg = new AlertDialog[1];
        final List<CheckBox> subChecks = new ArrayList<>();
        // "Watch directly" button: stream without downloading.
        if (!videoItems.isEmpty()) {
            Button watchBtn = new Button(act);
            watchBtn.setText("\u25b6 " + act.getString(R.string.watch_direct));
            watchBtn.setBackgroundColor(0xFFC81E1E);
            watchBtn.setTextColor(0xFFFFFFFF);
            float wd = act.getResources().getDisplayMetrics().density;
            LinearLayout.LayoutParams wlp = new LinearLayout.LayoutParams(
                    LinearLayout.LayoutParams.MATCH_PARENT,
                    (int) (48 * wd));
            int wm = (int) (12 * wd);
            wlp.setMargins(wm, wm / 2, wm, wm / 2);
            watchBtn.setLayoutParams(wlp);
            // Pick the best progressive (has audio) stream for watching.
            Item best = null;
            for (Item it : videoItems) {
                if (it.audioUrl == null && !"sub".equals(it.kind)) {
                    best = it; break;
                }
            }
            if (best == null) best = videoItems.get(0);
            final Item watchItem = best;
            watchBtn.setOnClickListener(v -> {
                dlg[0].dismiss();
                if (finishAfter) act.finish();
                PlayerActivity.watchStream(act, watchItem.url, title, vid);
            });
            root.addView(watchBtn, 0);
        }
        View.OnClickListener pick = v -> {
            Item it = (Item) v.getTag();
            dlg[0].dismiss();
            enqueueQuality(act, it, title, vid, durationSec,
                    subChecks, wifiDefault, finishAfter);
        };

        if (!videoItems.isEmpty()) {
            addSectionHeader(act, root, act.getString(R.string.sec_video));
            for (Item it : videoItems) root.addView(qualityRow(act, it, pick));
        }
        if (!audioItems.isEmpty()) {
            addSectionHeader(act, root, act.getString(R.string.sec_audio));
            for (Item it : audioItems) root.addView(qualityRow(act, it, pick));
        }
        if (!subItems.isEmpty() || !arEnSubs.isEmpty()) {
            addSectionHeader(act, root, act.getString(R.string.sec_sub));
            // "Also download with the video": AR / EN choice.
            if (!arEnSubs.isEmpty()) {
                LinearLayout subRow = new LinearLayout(act);
                subRow.setOrientation(LinearLayout.HORIZONTAL);
                int cp = (int) (16 * density);
                subRow.setPadding(cp, cp / 2, cp, 0);
                TextView lbl = new TextView(act);
                lbl.setText(act.getString(R.string.sub_also2));
                subRow.addView(lbl);
                for (SubtitlesStream st : arEnSubs) {
                    CheckBox cb = new CheckBox(act);
                    String tag = String.valueOf(st.getLanguageTag())
                            .toLowerCase(java.util.Locale.US);
                    cb.setText(tag.startsWith("ar")
                            ? act.getString(R.string.lang_ar)
                            : act.getString(R.string.lang_en));
                    cb.setTag(st);
                    subRow.addView(cb);
                    subChecks.add(cb);
                }
                root.addView(subRow);
            }
            for (Item it : subItems) root.addView(qualityRow(act, it, pick));
        }

        dlg[0] = new AlertDialog.Builder(act)
                .setTitle(title)
                .setView(sv)
                // Explicit listener: a null listener would NOT trigger
                // OnCancelListener, stranding the transparent ShareActivity
                // when the user taps Cancel instead of the back button.
                .setNegativeButton(R.string.btn_cancel,
                        (d, w) -> { if (finishAfter) act.finish(); })
                .setOnCancelListener(d -> { if (finishAfter) act.finish(); })
                .create();
        dlg[0].show();
        roundDialog(dlg[0], act);
    }

