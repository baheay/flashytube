    /**
     * @param subMap optional per-video subfolder (by video page URL);
     *               when set, the single-folder checkbox is hidden.
     */
    public static void pickBulkQuality(final Activity act,
                                       final List<StreamInfoItem> videos,
                                       final String listName,
                                       final boolean wifiOnly,
                                       final Map<String, String> subMap) {
        final ProgressDialog pd = new ProgressDialog(act);
        pd.setMessage(act.getString(R.string.prog_fetch));
        final AtomicBoolean cancelled = new AtomicBoolean(false);
        pd.setCancelable(true);
        pd.setOnCancelListener(d -> cancelled.set(true));
        pd.show();
        new Thread(() -> {
            try {
                ensureInit();
                StreamingService service = ServiceList.YouTube;
                StreamExtractor ex =
                        service.getStreamExtractor(videos.get(0).getUrl());
                ex.fetchPage();
                if (cancelled.get()) return;
                final List<BulkOpt> opts = new ArrayList<>();

                // Per-height pick: progressive first, else AVC video-only + AAC
                // mux (merged on-device). 1080 keeps "best >= 1080" behavior.
                int[] heights = {1080, 720, 480, 360, 240, 144};
                int[] qcs = {Q_VIDEO_1080, Q_VIDEO_720, Q_VIDEO_480,
                             Q_VIDEO_360, Q_VIDEO_240, Q_VIDEO_144};
                java.util.Set<String> seenQ = new java.util.HashSet<>();
                Set<String> burls = new LinkedHashSet<>();
                List<HeightOpt> hopts = new ArrayList<>();
                for (int i = 0; i < heights.length; i++) {
                    HeightOpt ho = pickHeightOpt(ex, heights[i]);
                    if (ho.video == null) continue;
                    String cu = String.valueOf(ho.video.getContent());
                    if (!seenQ.add(cu)) continue; // dedupe same stream
                    ho.quality = qcs[i];
                    hopts.add(ho);
                    burls.add(ho.video.getContent());
                    if (ho.audio != null) burls.add(ho.audio.getContent());
                }
                AudioStream bestA = bestAudioAny(ex);
                if (bestA != null) burls.add(bestA.getContent());
                Map<String, Long> bsizes = probeSizesParallel(burls, cancelled);
                if (cancelled.get()) return;
                for (HeightOpt ho : hopts) {
                    long sz = sizeOf(bsizes, ho.video.getContent());
                    if (ho.audio != null) sz += sizeOf(bsizes, ho.audio.getContent());
                    String name;
                    String lblRes;
                    if (ho.quality == Q_VIDEO_1080) {
                        name = act.getString(R.string.fmt_q_high,
                                ho.video.getResolution());
                        lblRes = ho.video.getResolution();
                    } else {
                        name = act.getString(qStringRes(ho.quality));
                        lblRes = qResName(ho.quality);
                    }
                    opts.add(new BulkOpt(ho.quality, name,
                            qLabel(act, true, lblRes, 0, sz)));
                }
                if (bestA != null) {
                    opts.add(new BulkOpt(Q_AUDIO,
                            act.getString(R.string.q_audio),
                            qLabel(act, false, null, bestA.getAverageBitrate(),
                                    sizeOf(bsizes, bestA.getContent()))));
                }

                act.runOnUiThread(() -> {
                    if (cancelled.get() || uiGone(act)) return;
                    pd.dismiss();
                    if (opts.isEmpty()) {
                        Toast.makeText(act, R.string.toast_no_qualities,
                                Toast.LENGTH_LONG).show();
                        return;
                    }
                    String[] labels = new String[opts.size()];
                    for (int i = 0; i < opts.size(); i++) labels[i] = opts.get(i).label;
                    AlertDialog bd = new AlertDialog.Builder(act)
                            .setTitle(act.getString(R.string.title_bulk_q, videos.size()))
                            .setItems(labels, (d, which) ->
                                    confirmBulkDownload(act, videos, opts.get(which), listName, wifiOnly, subMap))
                            .show();
                    roundDialog(bd, act);
                });
            } catch (Exception e) {
                if (cancelled.get()) return;
                fail(act, pd, e, false);
            }
        }).start();
    }

    /**
     * Confirmation step for bulk downloads: the dialog shows immediately and the
     * TOTAL estimated size is filled in when the background probes finish, so
     * there is no blocking "calculating" spinner.
     */
    private static void confirmBulkDownload(final Activity act,
                                            final List<StreamInfoItem> videos,
                                            final BulkOpt opt,
                                            final String listName,
                                            final boolean wifiOnly,
                                            final Map<String, String> subMap) {
        final long free = freeSpace();
        final String freeStr = free > 0 ? fmtSize(free)
                : act.getString(R.string.size_unknown);
        final String[] sizeStr = { "\u2026" };
        final String[] verdict = { "" };
        final TextView msgTv = new TextView(act);
        final Runnable refreshMsg = () -> msgTv.setText(
                act.getString(R.string.confirm_bulk_msg,
                        opt.name, videos.size(), sizeStr[0], freeStr + verdict[0]));
        refreshMsg.run();
        // Optional subfolder named after the playlist/channel.
        // With per-video subfolders (playlists tab) the structure is fixed.
        final String folderName = (subMap != null
                || listName == null || listName.trim().isEmpty())
                ? null : clean(listName);
        LinearLayout layout = new LinearLayout(act);
        layout.setOrientation(LinearLayout.VERTICAL);
        int pad = (int) (20 * act.getResources().getDisplayMetrics().density + 0.5f);
        layout.setPadding(pad, pad / 2, pad, 0);
        layout.addView(msgTv);
        final CheckBox folderBox;
        if (folderName != null) {
            folderBox = new CheckBox(act);
            folderBox.setText("\uD83D\uDCC1 " + folderName);
            folderBox.setChecked(true);
            layout.addView(folderBox);
        } else {
            folderBox = null;
        }
        LinearLayout subRow = new LinearLayout(act);
        subRow.setOrientation(LinearLayout.HORIZONTAL);
        TextView subLabel = new TextView(act);
        subLabel.setText("\uD83D\uDCDD " + act.getString(R.string.bulk_subtitles));
        subRow.addView(subLabel);
        final CheckBox subArBox = new CheckBox(act);
        subArBox.setText(act.getString(R.string.lang_ar));
        subRow.addView(subArBox);
        final CheckBox subEnBox = new CheckBox(act);
        subEnBox.setText(act.getString(R.string.lang_en));
        subRow.addView(subEnBox);
        layout.addView(subRow);
        AlertDialog cdlg = new AlertDialog.Builder(act)
                .setTitle(R.string.title_confirm)
                .setView(layout)
                .setPositiveButton(R.string.btn_download, (d, w) -> {
                    String kind = opt.quality == Q_AUDIO ? "audio" : "video";
                    String sub = (folderBox != null && folderBox.isChecked())
                            ? folderName : null;
                    DlEngine eng = DlEngine.get(act);
                    boolean wo = wifiOnly;
                    // Batch enqueue: one save + one notify for the whole list
                    // (per-item saves froze the UI on big channels).
                    List<DlEngine.BulkVideo> batch = new ArrayList<>(videos.size());
                    for (StreamInfoItem v : videos) {
                        DlEngine.BulkVideo bv = new DlEngine.BulkVideo();
                        bv.pageUrl = v.getUrl();
                        bv.baseName = clean(v.getName());
                        bv.quality = opt.quality;
                        bv.kind = kind;
                        bv.durationSec = v.getDuration();
                        bv.subfolder = subMap != null
                                ? subMap.get(v.getUrl()) : sub;
                        bv.wifiOnly = wo;
                        bv.subLang = (subArBox.isChecked() ? 1 : 0)
                                | (subEnBox.isChecked() ? 2 : 0);
                        batch.add(bv);
                    }
                    eng.enqueueBulkVideos(batch);
                    Toast.makeText(act,
                            act.getString(R.string.toast_bulk_added, videos.size()),
                            Toast.LENGTH_LONG).show();
                })
                .setNegativeButton(R.string.btn_cancel, null)
                .create();
        final AtomicBoolean cancelled = new AtomicBoolean(false);
        cdlg.setOnDismissListener(d -> cancelled.set(true));
        cdlg.show();
        roundDialog(cdlg, act);
        // Size estimate by sampling: probe up to 10 evenly-spaced videos and
        // extrapolate — probing hundreds of videos one by one took forever.
        new Thread(() -> {
            final int n = videos.size();
            final int sampleN = Math.min(10, n);
            List<StreamInfoItem> sample = new ArrayList<>(sampleN);
            for (int i = 0; i < sampleN; i++) {
                sample.add(videos.get((int) ((long) i * n / sampleN)));
            }
            ExecutorService probers = Executors.newFixedThreadPool(4);
            List<Future<Long>> futures = new ArrayList<>();
            for (StreamInfoItem v : sample) {
                final String pageUrl = v.getUrl();
                futures.add(probers.submit(() -> probeVideoSize(pageUrl, opt.quality)));
            }
            probers.shutdown();
            long sampleTotal = 0;
            int sampleOk = 0;
            try {
                for (Future<Long> f : futures) {
                    if (cancelled.get()) break;
                    long sz = f.get(45, TimeUnit.SECONDS);
                    if (sz > 0) { sampleTotal += sz; sampleOk++; }
                }
            } catch (Exception ignored) {}
            probers.shutdownNow();
            if (cancelled.get()) return;
            final boolean unknownF = sampleOk == 0;
            final long totalF = unknownF ? 0
                    : sampleTotal * n / Math.max(1, sampleOk);
            act.runOnUiThread(() -> {
                if (cancelled.get() || uiGone(act)) return;
                try {
                    if (!cdlg.isShowing()) return;
                } catch (Exception ignored) {
                    return;
                }
                sizeStr[0] = unknownF ? act.getString(R.string.size_unknown)
                        : fmtSize(totalF);
                verdict[0] = "";
                if (!unknownF && free > 0) {
                    verdict[0] = free > totalF ? act.getString(R.string.space_ok)
                            : act.getString(R.string.space_no);
                }
                refreshMsg.run();
            });
        }).start();
    }

    private static long probeVideoSize(String pageUrl, int quality) {
        try {
            Resolved r = resolveStream(pageUrl, quality);
            if (r == null) return 0;
            long s = Math.max(probeSize(r.url), 0);
            if (r.muxAudioUrl != null) s += Math.max(probeSize(r.muxAudioUrl), 0);
            return s;
        } catch (Exception e) {
            return 0;
        }
    }

    private static long freeSpace() {
        try {
            return Environment.getExternalStorageDirectory().getFreeSpace();
        } catch (Exception e) {
            return -1;
        }
    }

    /** Picked stream(s) for one target height. */
    static class HeightOpt {
        int quality;
        VideoStream video;
        AudioStream audio; // non-null => mux video-only + audio on-device
    }

    /**
     * Best stream(s) for a target height: progressive <= H first, else best
     * AVC video-only <= H + best AAC (muxed on-device). For H >= 1080 keeps
     * the "best at-or-above 1080p" behavior.
     */
    private static HeightOpt pickHeightOpt(StreamExtractor ex, int h)
            throws Exception {
        HeightOpt o = new HeightOpt();
        List<VideoStream> avc = new ArrayList<>();
        List<VideoStream> vp9 = new ArrayList<>();
        if (h >= 1080) {
            collectVideoOnly(ex, avc, vp9);
            VideoStream best = null;
            int bestH = 0;
            for (VideoStream v : avc) {
                int vh = parseHeight(v.getResolution());
                if (vh >= 1080 && vh > bestH) { best = v; bestH = vh; }
            }
            AudioStream aac = bestM4a(ex);
            if (best != null && aac != null) {
                o.video = best;
                o.audio = aac;
            }
            return o;
        }
        VideoStream prog = bestProgressive(ex, h);
        if (prog != null) {
            o.video = prog;
            return o;
        }
        collectVideoOnly(ex, avc, vp9);
        VideoStream best = null;
        int bestH = -1;
        for (VideoStream v : avc) {
            int vh = parseHeight(v.getResolution());
            if (vh > 0 && vh <= h && vh > bestH) { best = v; bestH = vh; }
        }
        AudioStream aac = bestM4a(ex);
        if (best != null && aac != null) {
            o.video = best;
            o.audio = aac;
        }
        return o;
    }

    private static AudioStream bestM4a(StreamExtractor ex) throws Exception {
        AudioStream aac = null;
        for (AudioStream a : ex.getAudioStreams()) {
            if (a.getFormat() != MediaFormat.M4A) continue;
            if (aac == null || a.getAverageBitrate() > aac.getAverageBitrate()) {
                aac = a;
            }
        }
        return aac;
    }

    private static AudioStream bestAudioAny(StreamExtractor ex) throws Exception {
        AudioStream best = null;
        for (AudioStream a : ex.getAudioStreams()) {
            int br = a.getAverageBitrate();
            if (br <= 0) continue;
            if (best == null || br > best.getAverageBitrate()) best = a;
        }
        return best;
    }

