    private static void enqueueQuality(Activity act, Item it, String title,
                                       String vid, long durationSec,
                                       List<CheckBox> subChecks,
                                       boolean wifiOnly,
                                       boolean finishAfter) {
        DlEngine eng = DlEngine.get(act);
        boolean wo = wifiOnly;
        if (it.audioUrl != null) {
            eng.enqueueMux(it.url, it.audioUrl, it.fileName, vid, durationSec,
                    it.muxHeight, it.muxWebm, wo);
        } else {
            eng.enqueue(it.url, it.fileName, it.kind, vid, durationSec, wo);
        }
        // "Also download" subtitles: one task per checked language.
        if (!"sub".equals(it.kind) && subChecks != null) {
            for (CheckBox cb : subChecks) {
                if (cb == null || !cb.isChecked()) continue;
                Object tag = cb.getTag();
                if (!(tag instanceof SubtitlesStream)) continue;
                SubtitlesStream st = (SubtitlesStream) tag;
                String sf = title + "." + st.getLanguageTag() + "."
                        + st.getExtension();
                eng.enqueue(st.getContent(), sf, "sub", vid, durationSec, wo);
            }
        }
        Toast.makeText(act, R.string.toast_added, Toast.LENGTH_SHORT).show();
        if (finishAfter) act.finish();
    }

