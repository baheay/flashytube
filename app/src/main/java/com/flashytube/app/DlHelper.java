    /**
     * Arabic + English subtitle streams for a video (VTT preferred, TTML
     * fallback). Prefers human-made over auto-generated. No network beyond
     * the already-fetched extractor page.
     */
    public static List<SubtitlesStream> pickArEnSubtitles(StreamExtractor ex) {
        List<SubtitlesStream> out = new ArrayList<>();
        try {
            List<SubtitlesStream> subs = ex.getSubtitles(MediaFormat.VTT);
            if (subs.isEmpty()) subs = ex.getSubtitles(MediaFormat.TTML);
            SubtitlesStream ar = null, arAuto = null, en = null, enAuto = null;
            for (SubtitlesStream st : subs) {
                String tag = String.valueOf(st.getLanguageTag()).toLowerCase();
                boolean auto = st.isAutoGenerated();
                if (tag.startsWith("ar")) {
                    if (!auto && ar == null) ar = st;
                    else if (auto && arAuto == null) arAuto = st;
                } else if (tag.startsWith("en")) {
                    if (!auto && en == null) en = st;
                    else if (auto && enAuto == null) enAuto = st;
                }
            }
            if (ar != null) out.add(ar); else if (arAuto != null) out.add(arAuto);
            if (en != null) out.add(en); else if (enAuto != null) out.add(enAuto);
        } catch (Exception ignored) {}
        return out;
    }

    /** Fresh fetch of AR/EN subtitles for a video page (fallback path). */
    public static List<SubtitlesStream> fetchArEnSubtitles(String pageUrl) {
        try {
            ensureInit();
            StreamingService service = ServiceList.YouTube;
            StreamExtractor ex = service.getStreamExtractor(pageUrl);
            ex.fetchPage();
            return pickArEnSubtitles(ex);
        } catch (Exception ignored) {
            return new ArrayList<>();
        }
    }

    public static void ensureInit() {
        if (NewPipe.getDownloader() == null) NewPipe.init(new SimpleDownloader());
        // Multi-client fallback (on-device "hybrid"): also fetch the iOS
        // player response for every video. getItags() merges Android + iOS +
        // VisionOS streams, so when YouTube blocks/throttles one client the
        // others still yield download URLs. No server involved.
        try {
            org.schabi.newpipe.extractor.services.youtube.extractors
                    .YoutubeStreamExtractor.setFetchIosClient(true);
        } catch (Exception ignored) {}
    }

    public static String extractYoutubeUrl(String text) {
        if (text == null) return null;
        Matcher m = Pattern.compile("https?://[^\\s\"']+").matcher(text);
        while (m.find()) {
            String u = m.group();
            if (u.contains("youtube.com") || u.contains("youtu.be")) return u;
        }
        return null;
    }

