    public static String clean(String s) {
        if (s == null || s.isEmpty()) return "video";
        s = s.replaceAll("[\\\\/:*?\"<>|]", "").trim().replaceAll("\\s+", " ");
        s = stripTrailingMediaExt(s);
        return s.length() > 80 ? s.substring(0, 80) : s;
    }

    /** "My Title.webm" -> "My Title": uploaders sometimes put the container
     *  in the title itself, and we append the real extension afterwards —
     *  without this the file ends up "Title.webm.webm". */
    private static String stripTrailingMediaExt(String s) {
        String lower = s.toLowerCase();
        String[] exts = {".mp4", ".webm", ".mp3", ".m4a",
                         " mp4", " webm", " mp3", " m4a"};
        for (String e : exts) {
            if (lower.endsWith(e)) {
                String cut = s.substring(0, s.length() - e.length()).trim();
                if (!cut.isEmpty()) return cut;
            }
        }
        return s;
    }

