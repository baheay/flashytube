    /** Friendly Arabic message for fetch failures.
     *  YouTube often temp-blocks anonymous requests per IP (very common on
     *  mobile carrier NATs) — detect that and explain the fix instead of
     *  showing the raw English extractor error. */
    public static String friendlyFetchError(Context ctx, Exception e) {
        String m = e == null ? "" : String.valueOf(e.getMessage());
        String ml = m.toLowerCase();
        if (e instanceof org.schabi.newpipe.extractor.exceptions.AgeRestrictedContentException) {
            return ctx.getString(R.string.err_age_restricted)
                    + "\n" + GoogleLogin.authDiagnostic();
        }
        if (ml.contains("blocked") || ml.contains("429")
                || ml.contains("too many requests")) {
            return ctx.getString(R.string.err_yt_blocked);
        }
        return m.length() > 90 ? m.substring(0, 90) : m;
    }

    private static void fail(Activity act, ProgressDialog pd, Exception e,
                             boolean finishAfter) {
        final String why = friendlyFetchError(act, e);
        final boolean ageRestricted = e instanceof org.schabi.newpipe.extractor
                .exceptions.AgeRestrictedContentException;
        act.runOnUiThread(() -> {
            try { pd.dismiss(); } catch (Exception ignored) {}
            if (uiGone(act)) return;
            if (ageRestricted) {
                showAgeRestrictedDialog(act, why, finishAfter);
                return;
            }
            Toast.makeText(act, act.getString(R.string.err_fetch, why),
                    Toast.LENGTH_LONG).show();
            if (finishAfter) act.finish();
        });
    }

    /** Age-restricted: dialog with diagnostic + age-verification hint. */
    private static void showAgeRestrictedDialog(final Activity act,
                                                final String why,
                                                final boolean finishAfter) {
        String d0 = GoogleLogin.authDiagnostic();
        if (WebPlayer.lastReason != null && !WebPlayer.lastReason.isEmpty()) {
            d0 += "\nweb: " + WebPlayer.lastReason;
        }
        final String diag = d0;
        android.widget.LinearLayout layout =
                new android.widget.LinearLayout(act);
        layout.setOrientation(android.widget.LinearLayout.VERTICAL);
        int p = (int) (16 * act.getResources().getDisplayMetrics().density);
        layout.setPadding(p, p, p, p);

        android.widget.TextView msg = new android.widget.TextView(act);
        msg.setText(why);
        msg.setTextSize(14);
        layout.addView(msg);

        android.widget.TextView d = new android.widget.TextView(act);
        d.setText("\n" + diag);
        d.setTextSize(12);
        d.setTextIsSelectable(true);
        layout.addView(d);

        android.widget.TextView hint = new android.widget.TextView(act);
        hint.setText("\n" + act.getString(R.string.err_age_hint));
        hint.setTextSize(13);
        layout.addView(hint);

        android.app.AlertDialog dlg = new android.app.AlertDialog.Builder(act)
                .setTitle(act.getString(R.string.err_age_title))
                .setView(layout)
                .setPositiveButton(act.getString(R.string.err_age_copy),
                        (dd, w) -> {
                            android.content.ClipboardManager cm =
                                    (android.content.ClipboardManager) act
                                        .getSystemService(
                                            android.content.Context
                                                .CLIPBOARD_SERVICE);
                            cm.setPrimaryClip(android.content.ClipData
                                    .newPlainText("age", diag));
                            android.widget.Toast.makeText(act,
                                    R.string.crash_copied,
                                    android.widget.Toast.LENGTH_SHORT).show();
                        })
                .setNegativeButton(android.R.string.cancel, (dd, w) -> {
                    if (finishAfter) act.finish();
                })
                .setOnCancelListener(dd -> {
                    if (finishAfter) act.finish();
                })
                .create();
        dlg.show();
        roundDialog(dlg, act);
    }

    /** Formats an upload DateWrapper as dd/MM/yyyy, or "" when unavailable. */
    public static String fmtUploadDate(DateWrapper dw) {
        if (dw == null) return "";
        try {
            // Numeric: compact and RTL-safe (no wrap/jumble like "12 Oct 2022").
            return dw.offsetDateTime().format(
                    DateTimeFormatter.ofPattern("dd/MM/yyyy"));
        } catch (Exception e) {
            return "";
        }
    }

    public static String guessMime(String name) {        String n = name.toLowerCase();
        if (n.endsWith(".mp4")) return "video/mp4";
        if (n.endsWith(".webm")) return "video/webm";
        if (n.endsWith(".mkv")) return "video/x-matroska";
        if (n.endsWith(".m4a")) return "audio/mp4";
        if (n.endsWith(".mp3")) return "audio/mpeg";
        if (n.endsWith(".opus") || n.endsWith(".ogg")) return "audio/ogg";
        if (n.endsWith(".vtt")) return "text/vtt";
        if (n.endsWith(".srt")) return "application/x-subrip";
        if (n.endsWith(".ttml")) return "application/ttml+xml";
        return "application/octet-stream";
    }

    public static void openCompleted(Context ctx, DlEngine.Task t) {
        try {
            if (t.publishedUri == null || t.publishedUri.isEmpty()) {
                Toast.makeText(ctx, R.string.toast_open_where, Toast.LENGTH_LONG).show();
                return;
            }
            Intent i = new Intent(Intent.ACTION_VIEW);
            i.setDataAndType(Uri.parse(t.publishedUri), guessMime(t.fileName));
            i.addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION
                    | Intent.FLAG_ACTIVITY_NEW_TASK);
            ctx.startActivity(i);
        } catch (Exception e) {
            Toast.makeText(ctx, R.string.toast_open_fail, Toast.LENGTH_SHORT).show();
        }
    }

    /** Open a completed download: try the in-app player, fall back to external app. */
    public static void playTask(Activity act, DlEngine.Task t) {
        if (t == null || t.state != DlEngine.State.COMPLETED) return;
        // Audio never opens the full player: it plays in the mini bar.
        if ("audio".equals(t.kind)) {
            AudioPlayer.get(act).play(t);
            return;
        }
        try {
            Intent i = new Intent(act, PlayerActivity.class);
            i.putExtra("task_id", t.id);
            act.startActivity(i);
        } catch (Exception e) {
            openCompleted(act, t);
        }
    }
