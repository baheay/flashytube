    /** Load all pages of a playlist/channel tab (30 items per page), with a live counter. */
    private static void collectAll(final Activity act, final ProgressDialog pd,
                                   final ListExtractor<? extends InfoItem> ex,
                                   final List<StreamInfoItem> out,
                                   final List<PlaylistInfoItem> playlistsOut,
                                   final String baseMsg,
                                   final AtomicBoolean cancelled) throws Exception {
        ListExtractor.InfoItemsPage<? extends InfoItem> page = ex.getInitialPage();
        int pageNum = 0;
        while (page != null && pageNum < 20) { // cap: 20 pages ≈ 600 videos
            if (cancelled != null && cancelled.get()) break;
            pageNum++;
            for (InfoItem item : page.getItems()) {
                if (item instanceof StreamInfoItem) out.add((StreamInfoItem) item);
                else if (playlistsOut != null && item instanceof PlaylistInfoItem) {
                    playlistsOut.add((PlaylistInfoItem) item);
                }
            }
            final int count = out.size();
            act.runOnUiThread(() -> {
                try { pd.setMessage(baseMsg + " (" + count + ")"); }
                catch (Exception ignored) {}
            });
            Page next = page.getNextPage();
            if (!Page.isValid(next)) break;
            page = ex.getPage(next);
        }
    }

